"""Build Panabo's indicative barangay areas; never use household coordinates.

Source is NAMRIA/PSA geometry repackaged by barangay-boundaries-repository.
Run with the downloaded 2023-10-24/hierarchical_t0p005/barangays.geojson path.
The centroid is a display approximation, not a home or routing destination.
"""
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
rows = []
for feature in json.loads(source.read_text(encoding='utf-8'))['features']:
    p = feature['properties']
    if p.get('ADM3_PCODE') != 'PH1102315':
        continue
    geometry = feature['geometry']
    polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    # Use the largest polygon's signed-area centroid, not a user's coordinates.
    ring = max(polygons, key=lambda x: len(x[0]))[0]
    area = cx = cy = 0
    for a, b in zip(ring, ring[1:]):
        cross = a[0] * b[1] - b[0] * a[1]
        area += cross
        cx += (a[0] + b[0]) * cross
        cy += (a[1] + b[1]) * cross
    name = p['ADM4_EN'].replace('Ni\ufffdo', 'Ni\u00f1o')
    rows.append(dict(id=p['psgc_code'], name=name, latitude=round(cy / (3 * area), 6),
                     longitude=round(cx / (3 * area), 6), polygons=polygons))
assert len(rows) == 40 and len({r['id'] for r in rows}) == 40
rows.sort(key=lambda r: r['name'])
data = dict(version=1, source='https://github.com/bendlikeabamboo/barangay-boundaries-repository/blob/main/2023-10-24/hierarchical_t0p005/barangays.geojson',
            sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            notice='Indicative NAMRIA/PSA boundaries (2023 snapshot). Not legal boundaries. Centers and distances are approximate.', barangays=rows)
(root / 'functions/panabo_barangays.json').write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
dart = "// Generated by scripts/build_barangay_catalog.py. Do not edit.\nconst panaboBarangays = <Map<String, dynamic>>" + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n'
(root / 'lib/data').mkdir(exist_ok=True)
(root / 'lib/data/panabo_barangays.dart').write_text(dart, encoding='utf-8')
print(f'Generated {len(rows)} barangays')
