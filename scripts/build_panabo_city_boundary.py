"""Generate the city envelope used to limit indicative barangay gap handling.

Pass the source component_cities.geojson from the same snapshot as the barangays.
No provider or customer coordinates are used to generate geographic data.
"""
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[1]
source = Path(sys.argv[1])
features = json.loads(source.read_text(encoding='utf-8'))['features']
feature = next(f for f in features if f['properties'].get('psgc_code') == '1102315000')
geometry = feature['geometry']
polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
data = dict(
    source='https://github.com/bendlikeabamboo/barangay-boundaries-repository/blob/main/2023-10-24/hierarchical_t0p005/component_cities.geojson',
    sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),
    notice='Indicative NAMRIA/PSA city boundary. Not a legal boundary. See docs/barangay-data-license.txt.',
    # The upstream shapes were independently simplified with this tolerance.
    gapToleranceDegrees=0.005,
    polygons=polygons,
)
(root / 'functions/panabo_city.json').write_text(json.dumps(data, separators=(',', ':')) + '\n', encoding='utf-8')
dart = '// Generated by scripts/build_panabo_city_boundary.py. Do not edit.\n'
dart += 'const panaboCoverageGapToleranceDegrees = 0.005;\n'
dart += 'const panaboCityPolygons = <List<dynamic>>' + json.dumps(polygons, separators=(',', ':')) + ';\n'
(root / 'lib/data/panabo_city.dart').write_text(dart, encoding='utf-8')
print('Generated Panabo city envelope')
