"""Create small bundled thumbnails; retain the original photographs unchanged."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT=Path(__file__).resolve().parent.parent
sources=json.loads((ROOT/'scripts/service-image-sources.json').read_text(encoding='utf-8'))
destination=ROOT/'assets/optimized_services'
destination.mkdir(parents=True,exist_ok=True)
paths={}
records=[]
for key,source in sources.items():
    original=ROOT/source
    name=key.replace('|','-').replace(' ','-')+'.webp'
    target=destination/name
    with Image.open(original) as image:
        image=ImageOps.exif_transpose(image).convert('RGB')
        image.thumbnail((1200,1200),Image.Resampling.LANCZOS)
        image.save(target,'WEBP',quality=80,method=6)
        width,height=image.size
    paths[key]=target.relative_to(ROOT).as_posix()
    records.append({'key':key,'source':source,'source_bytes':original.stat().st_size,'source_sha256':hashlib.sha256(original.read_bytes()).hexdigest(),
                    'bundled_path':paths[key],'bundled_bytes':target.stat().st_size,'width':width,'height':height})
dart="// Generated by scripts/optimize-service-images.py; originals are preserved.\nabstract final class MarketingServiceAssetPaths {\n  static const byCategoryAndName = <String, String>{\n"
dart+=''.join(f"    '{key}': '{path}',\n" for key,path in paths.items())+"  };\n}\n"
(ROOT/'lib/figma_ui/marketing_service_asset_paths.dart').write_text(dart,encoding='utf-8')
report={'original_catalog_bytes':sum(p.stat().st_size for p in (ROOT/'assets/service_picture').rglob('*') if p.is_file()),
        'selected_source_bytes':sum(r['source_bytes'] for r in records),'bundled_service_image_bytes':sum(r['bundled_bytes'] for r in records),
        'images':records,'codec':'WebP quality 80; maximum 1200 x 1200; EXIF metadata removed','originals_modified':False}
(ROOT/'docs/service-image-optimization.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print(json.dumps({k:v for k,v in report.items() if k!='images'}))
